// تبدأ بالعبارات (لتبقى الجملة سليمة) ثم الكلمات من الأطول للأقصر؛ تقبل سوابق الواو والفاء والباء واللام والكاف.
const PHRASES = [
  [/(?<![ء-ي])(ال)?تبرع\s+ب(ال)?/g, (m, a, b) => 'طلب ' + (b || '')], // «التبرع بالماء» ← «طلب الماء»
  [/(تتبرع|تبرع|تبرّع|يتبرع|نتبرع|أتبرع|اتبرع)\s+(بها|به|بهم|بهن)/g, (m, v, p) => ({ تتبرع: 'تطلب', يتبرع: 'يطلب', نتبرع: 'نطلب', أتبرع: 'أطلب', اتبرع: 'اطلب' }[v] || 'تطلب') + { بها: 'ها', به: 'ه', بهم: 'هم', بهن: 'هن' }[p]],
];
const WORDS = [
  ['المتبرعين', 'العملاء'], ['المتبرعون', 'العملاء'], ['المتبرعة', 'العميلة'], ['المتبرع', 'العميل'], ['متبرعين', 'عملاء'], ['متبرعون', 'عملاء'], ['متبرعة', 'عميلة'], ['متبرع', 'عميل'],
  ['تبرعاتكم', 'طلباتكم'], ['تبرعاتك', 'طلباتك'], ['التبرعات', 'الطلبات'], ['تبرعات', 'طلبات'], ['تبرعكم', 'طلبكم'], ['تبرعك', 'طلبك'], ['التبرع', 'الطلب'],
  ['تتبرعون', 'تطلبون'], ['تتبرعين', 'تطلبين'], ['تتبرع', 'تطلب'], ['يتبرعون', 'يطلبون'], ['يتبرع', 'يطلب'], ['نتبرع', 'نطلب'], ['أتبرع', 'أطلب'], ['اتبرع', 'اطلب'],
  ['تبرّع', 'اطلب'], ['تبرع', 'طلب'],
];
const WORD_RE = new RegExp(`(?<![\\u0621-\\u064A])([وف]?[بلك]?)(${WORDS.map((w) => w[0]).join('|')})`, 'g');
const WORD_MAP = Object.fromEntries(WORDS);
export function moroojWording(text) {
  let s = String(text || '');
  for (const [re, fn] of PHRASES) s = s.replace(re, fn);
  return s.replace(WORD_RE, (m, pre, w) => pre + (WORD_MAP[w] || w));
}
