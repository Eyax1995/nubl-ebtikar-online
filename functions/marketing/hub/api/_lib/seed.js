export function catalogRows() {
  const rows = [];
  for (const s of SECTORS) {
    MATRIX[s.id].forEach((r, i) => {
      const [tname, months, plan, payText] = TERMS[i];
      rows.push({
        kind: 'package', sector: s.id, code: `PKG-${s.id.toUpperCase()}-${months}M`,
        name: `باقة ${s.name} — ${tname}`, months, monthly: r[0], price: r[1], unit: 'عقد',
        plan, delivery: payText,
        details: JSON.stringify({ posts: r[2], designs: r[3], platforms: r[4], adcap: r[5] }),
      });
    });
  }
  SERVICES.forEach(([g, name, price, unit, delivery, desc], i) => rows.push({
    kind: 'service', sector: g, code: `SRV-${String(i + 1).padStart(2, '0')}`, name, months: 0, monthly: 0, price, unit,
    plan: 'single', delivery, details: JSON.stringify({ desc }),
  }));
  PRINT.forEach(([name, price, unit], i) => rows.push({
    kind: 'print', sector: 'مطبوعات الكيان الأم', code: `PRN-${String(i + 1).padStart(2, '0')}`, name, months: 0, monthly: 0,
    price, unit, plan: 'single', delivery: '', details: '{}',
  }));
  return rows;
}

